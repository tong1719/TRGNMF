"""Run canonicalized TRGNMF on uniform and recent-paper protocols.

Two prespecified settings are retained separately:

1. ``uniform10`` uses 10% labels per class and selects ``k`` from
   ``{3,5,7,9}`` using the observed graph and labelled samples only;
2. ``snmfwlp2026`` follows the dataset constructions, label fractions, and graph
   sizes used for the four direct-protocol datasets reported by Jing et al.
   (Signal Processing 241, 2026, 110407).

Published comparator values are not generated by this script and must remain
explicitly identified as external published aggregates in the manuscript.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path

import numpy as np
from scipy.io import loadmat

from experiment_utils import K_VALUES, component_diagnostics
from run_validated_gate import labelled_cross_validation
from src.trgnmf import (
    canonicalize_nmf_factors,
    clamped_propagation,
    edge_agreement,
    evaluate_scores,
    gate_coefficient,
    nmf_factors,
    row_normalize,
    split_labels,
    transition_on_topology,
)


SEEDS = tuple(range(57810, 57820))
DATASETS = ("COIL20", "COIL100", "MNIST-20000", "TOX-156", "TOX-171", "USPS-5000")
REPORTED_FRACTION = {
    "COIL20": 0.05,
    "COIL100": 0.05,
    "MNIST-20000": 0.005,
    "TOX-156": 0.20,
}
REPORTED_K = {"COIL20": 3, "COIL100": 3, "MNIST-20000": 5, "TOX-156": 4}
SNMFWLP_PUBLISHED = {
    "COIL20": {"acc": 0.9357, "nmi": 0.9461},
    "COIL100": {"acc": 0.8451, "nmi": 0.9179},
    "MNIST-20000": {"acc": 0.9150, "nmi": 0.8298},
    "TOX-156": {"acc": 0.5774, "nmi": 0.3254},
}


def atomic_write(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(value, indent=2), encoding="utf-8")
    os.replace(temporary, path)


def file_hash(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def load_dataset(
    name: str,
    primary_dir: Path,
    image_dir: Path,
    subset_seed: int = 56800,
) -> tuple[np.ndarray, np.ndarray, dict[str, object]]:
    if name in {"COIL20", "COIL100"}:
        path = primary_dir / f"{name}.mat"
        data = loadmat(path)
        x = np.asarray(data["fea"], dtype=np.float32)
        _, y = np.unique(np.asarray(data["gnd"]).ravel(), return_inverse=True)
        metadata = {"source_file": path.name, "sha256": file_hash(path)}
    elif name == "MNIST-20000":
        path = image_dir / "MNIST.mat"
        data = loadmat(path)
        raw = np.vstack([data["train_fea"], data["test_fea"]]).astype(np.float32)
        raw_y = np.concatenate([data["train_gnd"].ravel(), data["test_gnd"].ravel()]).astype(int) - 1
        ids = np.concatenate([np.flatnonzero(raw_y == class_id)[:2000] for class_id in range(10)])
        x, y = raw[ids], raw_y[ids]
        metadata = {
            "source_file": path.name,
            "sha256": file_hash(path),
            "construction": "first 2000 samples per encoded class after train-test concatenation",
        }
    elif name in {"TOX-156", "TOX-171"}:
        path = image_dir / "TOX-171.mat"
        data = loadmat(path)
        raw = np.asarray(data["X"], dtype=np.float32)
        _, raw_y = np.unique(np.asarray(data["Y"]).ravel(), return_inverse=True)
        if name == "TOX-156":
            ids = np.concatenate(
                [np.flatnonzero(raw_y == class_id)[:39] for class_id in np.unique(raw_y)]
            )
            x, y = raw[ids, :5600], raw_y[ids]
            construction = "first 39 samples per encoded class and first 5600 features"
        else:
            x, y = raw, raw_y
            construction = "complete published TOX-171 matrix without sample or feature filtering"
        x = x - min(float(np.min(x)), 0.0)
        metadata = {
            "source_file": path.name,
            "sha256": file_hash(path),
            "construction": construction,
        }
    elif name == "USPS-5000":
        path = image_dir / "USPS11000_RAW.mat"
        cube = np.asarray(loadmat(path)["data"], dtype=np.float32)
        rng = np.random.default_rng(subset_seed)
        blocks = []
        labels = []
        for class_id in range(10):
            ids = rng.choice(1100, 500, replace=False)
            blocks.append(cube[:, ids, class_id].T)
            labels.extend([class_id] * 500)
        x, y = np.vstack(blocks), np.asarray(labels, dtype=int)
        metadata = {
            "source_file": path.name,
            "sha256": file_hash(path),
            "subset_seed": subset_seed,
            "construction": "fixed 500-sample subset per class",
        }
    else:
        raise KeyError(name)
    x = row_normalize(x).astype(np.float32)
    y = np.asarray(y, dtype=int)
    return x, y, metadata


def evaluate_setting(
    x: np.ndarray,
    y: np.ndarray,
    representation: np.ndarray,
    seed: int,
    label_fraction: float,
    neighbors: int,
    setting_name: str,
) -> dict[str, object]:
    labelled = split_labels(y, seed, fraction=label_fraction)
    rho, overlap = edge_agreement(x, representation, neighbors)
    candidate_coefficient, capped = gate_coefficient(rho, threshold=0.5, cap=0.75)
    permutation = np.random.default_rng(seed + 940_000).permutation(len(x))
    observed_transition = transition_on_topology(x, representation, neighbors, 0.0)
    candidate_transition = transition_on_topology(
        x, representation, neighbors, candidate_coefficient
    )
    validation = labelled_cross_validation(
        {
            "observed_graph": observed_transition,
            "candidate_refinement": candidate_transition,
        },
        y,
        labelled,
        seed + neighbors,
    )
    accepted = bool(
        candidate_coefficient > 0.0
        and validation["candidate_correct"] > validation["observed_correct"]
        and validation["positive_repeats"] >= 4
    )
    coefficient = candidate_coefficient if accepted else 0.0
    matched_strength = min(max(float(rho), 0.0), 0.75)
    values = {
        "observed_graph": (0.0, None),
        "TRGNMF": (coefficient, None),
        "candidate_refinement": (candidate_coefficient, None),
        "ungated_refinement": (matched_strength, None),
        "full_support": (1.0, None),
        "forced_shuffled": (matched_strength, permutation),
    }
    metrics = {}
    for arm, (value, perm) in values.items():
        transition = transition_on_topology(x, representation, neighbors, value, permutation=perm)
        scores = clamped_propagation(transition, y, labelled, len(np.unique(y)))
        metrics[arm] = evaluate_scores(y, scores, labelled)["unlabelled"]
    return {
        "setting": setting_name,
        "seed": seed,
        "label_fraction": label_fraction,
        "labelled": int(len(labelled)),
        "minimum_labels_per_class": int(
            min(np.sum(y[labelled] == class_id) for class_id in np.unique(y))
        ),
        "neighbors": neighbors,
        "rho": float(rho),
        "overlap": float(overlap),
        "candidate_coefficient": float(candidate_coefficient),
        "accepted": accepted,
        "coefficient": float(coefficient),
        "capped": bool(capped),
        "labelled_cross_validation": validation,
        "metrics": metrics,
        "components": component_diagnostics(x, labelled, neighbors),
    }


def run_dataset(
    name: str,
    primary_dir: Path,
    image_dir: Path,
    output_dir: Path,
    limit: int | None,
) -> None:
    x, y, metadata = load_dataset(name, primary_dir, image_dir)
    output = output_dir / f"{name}.json"
    records = json.loads(output.read_text(encoding="utf-8")) if output.exists() else []
    completed = {int(record["seed"]) for record in records}
    seeds = SEEDS if limit is None else SEEDS[:limit]
    for seed in seeds:
        if seed in completed:
            print(name, seed, "already complete", flush=True)
            continue
        raw_w, raw_h, iterations = nmf_factors(x, len(np.unique(y)), seed, max_iter=200)
        representation, _ = canonicalize_nmf_factors(raw_w, raw_h)
        uniform_grid = [
            evaluate_setting(
                x,
                y,
                representation.astype(np.float32),
                seed,
                0.10,
                neighbors,
                f"uniform10_k{neighbors}",
            )
            for neighbors in K_VALUES
        ]
        uniform_selected = max(
            uniform_grid,
            key=lambda row: (
                float(row["labelled_cross_validation"]["observed_accuracy"]),
                -int(row["neighbors"]),
            ),
        ).copy()
        uniform_selected["setting"] = "uniform10"
        uniform_selected["selection_rule"] = (
            "observed-graph labelled cross-validation; smallest k breaks ties"
        )
        settings = [uniform_selected]
        if name in REPORTED_FRACTION:
            settings.append(
                evaluate_setting(
                    x,
                    y,
                    representation.astype(np.float32),
                    seed,
                    REPORTED_FRACTION[name],
                    REPORTED_K[name],
                    "snmfwlp2026",
                )
            )
        records.append(
            {
                "dataset": name,
                "shape": list(x.shape),
                "classes": int(len(np.unique(y))),
                "seed": seed,
                "nmf_iterations": int(iterations),
                "factor_canonicalization": "component_l2",
                "data": metadata,
                "settings": settings,
                "uniform_k_grid": uniform_grid,
            }
        )
        records.sort(key=lambda record: int(record["seed"]))
        atomic_write(output, records)
        print(name, seed, "complete", flush=True)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("dataset", choices=(*DATASETS, "all"))
    parser.add_argument("--primary-dir", type=Path, required=True)
    parser.add_argument("--image-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, default=Path("results/uniform_recent_v3"))
    parser.add_argument("--limit", type=int, default=None)
    args = parser.parse_args()
    selected = DATASETS if args.dataset == "all" else (args.dataset,)
    for dataset in selected:
        run_dataset(dataset, args.primary_dir, args.image_dir, args.output_dir, args.limit)


if __name__ == "__main__":
    main()
